function makePreset(spec) {
  const isMissingFile = spec.assetStatus === 'missing_file';
  return {
    id: spec.id,
    name: spec.name,
    category: spec.category,
    tags: spec.tags || [],
    description: spec.description,
    asset: isMissingFile
      ? { type: 'audio_file', path: spec.filePath, synthRecipe: null }
      : { type: 'procedural_synth', path: `procedural://${spec.category}/${spec.id}`, synthRecipe: spec.synthRecipe || spec.id },
    assetStatus: isMissingFile ? 'missing_file' : 'ready_procedural',
    duration: spec.duration ?? 0.24,
    defaultVolume: spec.defaultVolume ?? 0.55,
    volumeRange: spec.volumeRange || [0.05, 1.0],
    pitch: spec.pitch ?? 1.0,
    playbackRate: spec.playbackRate ?? 1.0,
    fadeIn: spec.fadeIn ?? 0.006,
    fadeOut: spec.fadeOut ?? 0.04,
    cooldown: spec.cooldown ?? 0.35,
    priority: spec.priority ?? 5,
    intensity: spec.intensity || 'medium',
    mood: spec.mood || ['neutral'],
    contextTags: spec.contextTags || [],
    avoidTags: spec.avoidTags || [],
    loopable: Boolean(spec.loopable),
    defaultSpatialMode: spec.defaultSpatialMode || '2d',
    bus: spec.bus || 'sfx_secondary',
    license: isMissingFile
      ? 'External audio file required (user-supplied royalty-free WAV/OGG/MP3)'
      : 'PuppetKit Procedural Web Audio (Royalty-Free Built-in)',
    notes: spec.notes || '',
  };
}


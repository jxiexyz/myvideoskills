export class SFXPresetRegistry {
  constructor() {
    this._presets = new Map();
    this._defaults = new Map();
    this._combos = new Map();
    this._defaultCombos = new Map();

    for (const p of BUILTIN_SFX_PRESETS) {
      this._presets.set(p.id, structuredClone(p));
      this._defaults.set(p.id, structuredClone(p));
    }
    for (const c of BUILTIN_SFX_COMBINATIONS) {
      this._combos.set(c.id, structuredClone(c));
      this._defaultCombos.set(c.id, structuredClone(c));
    }
  }

  get(id) {
    return this._presets.get(id) || null;
  }

  list() {
    return Array.from(this._presets.values());
  }

  listCombinations() {
    return Array.from(this._combos.values());
  }

  getCombination(id) {
    return this._combos.get(id) || null;
  }

  search({ query = '', category = 'all', mood = 'all', intensity = 'all', maxDuration = null, assetStatus = 'all' } = {}) {
    const q = String(query || '').trim().toLowerCase();
    return this.list().filter((p) => {
      if (category !== 'all' && p.category !== category) return false;
      if (intensity !== 'all' && p.intensity !== intensity) return false;
      if (assetStatus !== 'all' && p.assetStatus !== assetStatus) return false;
      if (mood !== 'all' && !(p.mood || []).includes(mood)) return false;
      if (typeof maxDuration === 'number' && maxDuration > 0 && p.duration > maxDuration) return false;
      if (!q) return true;
      const haystack = [
        p.id,
        p.name,
        p.category,
        p.description,
        ...(p.tags || []),
        ...(p.contextTags || []),
        ...(p.mood || []),
      ]
        .join(' ')
        .toLowerCase();
      return haystack.includes(q);
    });
  }

  saveCustomPreset(presetInput) {
    const id = presetInput.id || `custom_${Date.now().toString(36)}`;
    const normalized = makePreset({
      ...presetInput,
      id,
      category: presetInput.category || 'ui',
      description: presetInput.description || 'Custom user SFX preset.',
    });
    this._presets.set(normalized.id, normalized);
    return normalized;
  }

  resetPreset(id) {
    const def = this._defaults.get(id);
    if (!def) return null;
    const restored = structuredClone(def);
    this._presets.set(id, restored);
    return restored;
  }

  saveCombination(combo) {
    if (!combo?.id) return null;
    const copy = structuredClone(combo);
    this._combos.set(copy.id, copy);
    return copy;
  }

  resetCombination(id) {
    const def = this._defaultCombos.get(id);
    if (!def) return null;
    const restored = structuredClone(def);
    this._combos.set(id, restored);
    return restored;
  }

  getMissingAssetsReport() {
    const all = this.list();
    const missing = all.filter((p) => p.assetStatus === 'missing_file');
    const readyProcedural = all.filter((p) => p.assetStatus === 'ready_procedural');
    return {
      totalPresets: all.length,
      readyProceduralCount: readyProcedural.length,
      missingFileCount: missing.length,
      missingPresets: missing.map((p) => ({
        id: p.id,
        name: p.name,
        category: p.category,
        expectedPath: p.asset.path,
        notes: p.notes,
      })),
    };
  }
}

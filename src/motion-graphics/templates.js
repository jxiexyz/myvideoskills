export const MOTION_GRAPHIC_TEMPLATE_LIST = Object.values(MOTION_GRAPHIC_TEMPLATES);

/**
 * Create a complete, normalized motion graphic configuration from a template ID + user overrides.
 */
export function createMotionGraphicConfig(templateId = 'million_dollar_reveal', overrides = {}) {
  const tpl = MOTION_GRAPHIC_TEMPLATES[templateId] || MOTION_GRAPHIC_TEMPLATES.million_dollar_reveal;
  return {
    template: tpl.id,
    layout: tpl.layout,
    category: tpl.category,
    content: overrides.content ?? tpl.defaultContent,
    subtitle: overrides.subtitle ?? tpl.defaultSubtitle,
    secondaryValue: overrides.secondaryValue ?? tpl.defaultSecondary,
    colorTheme: overrides.colorTheme ?? tpl.theme,
    outline: overrides.outline !== undefined ? Boolean(overrides.outline) : true,
    entrance: overrides.entrance ?? tpl.entrance,
    impact: overrides.impact ?? tpl.impact,
    continuous: overrides.continuous ?? tpl.continuous,
    exit: overrides.exit ?? tpl.exit,
    transition: overrides.transition ?? 'none',
    duration: Number.isFinite(overrides.duration) ? overrides.duration : 4.2,
    entranceDuration: Number.isFinite(overrides.entranceDuration) ? overrides.entranceDuration : 0.65,
    exitDuration: Number.isFinite(overrides.exitDuration) ? overrides.exitDuration : 0.55,
    soundCue: overrides.soundCue ?? tpl.soundCue ?? 'soft_pop',
    anchorName: overrides.anchorName ?? tpl.anchorName ?? null,
    position: overrides.position ?? 'top_center', // top_center | top_right | center | lower_third | auto
  };
}
